                code, optimized = invoke(binary, preset.read_bytes(), optimize=True)
                assert code == 0 and optimized.get("ok"), optimized
                number = preset.name[:2]
                for pattern in EXPECTED.get(number, ()):
                    assert re.search(pattern, optimized["ir"], re.DOTALL), pattern
                if number in ABSENT:
                    assert not re.search(ABSENT[number], optimized["ir"], re.MULTILINE), ABSENT[number]
                code, checked = invoke(binary, optimized["ir"].encode())
                assert code == 0 and checked.get("ok"), checked
